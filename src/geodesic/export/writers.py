"""File writers for evidence tables: Excel (linked sheets), CSV, JSON and RIS.

Layout conventions (stable, so exports can be read back by scripts):

* Excel: sheet ``README`` first. On every table sheet row 1 is a banner (data
  class and protocol status), row 2 the header, data from row 3. Columns that
  reference another table are internal hyperlinks to the referenced row.
  All text is written as text: a value starting with ``=`` is never a formula.
* CSV: UTF-8 with header row; the last column ``data_class`` repeats the
  project's data class on every row. Values are written exactly as stored.
* JSON: ``{"label", "project", "tables": {name: {"columns", "rows", "note"}}}``.
* RIS: one record per paper; ``N1`` carries the GEODESIC paper ID and status.

Files from a synthetic project are prefixed ``SYNTHETIC_`` and carry the
synthetic label inside.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path
from typing import Any

from openpyxl import Workbook
from openpyxl.cell import WriteOnlyCell
from openpyxl.cell.cell import ILLEGAL_CHARACTERS_RE
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.hyperlink import Hyperlink

from .. import __version__
from ..provenance import SYNTHETIC_LABEL
from ..util import utc_now
from .tables import Table

EXCEL_HEADER_ROW = 2
EXCEL_FIRST_DATA_ROW = 3
EXCEL_MAX_LINKS_PER_SHEET = 60_000      # Excel allows about 65,530 hyperlinks per sheet
EXCEL_MAX_ROWS = 1_048_576

_WIDE = {"source_wording": 60, "excerpt": 60, "citation_text": 50, "title": 45, "citation": 28, "location": 40,
         "source_location": 40, "interpretation_limits": 40, "definition": 50, "text": 60, "field_status": 40,
         "review_flags": 36, "qualifiers": 30, "authors": 30, "correction_retraction": 40}


def banner(info: dict[str, Any]) -> str:
    """One-line statement placed on every export."""
    parts = []
    if info["data_class"] == "synthetic":
        parts.append(SYNTHETIC_LABEL)
    else:
        parts.append("Project data class: real")
    parts.append(f"project '{info['project_name']}'")
    parts.append(f"protocol {info['protocol_version']}" + (
        "" if info["protocol_confirmed"] else " — eligibility criteria are provisional"))
    return " | ".join(parts)


def file_prefix(info: dict[str, Any]) -> str:
    return "SYNTHETIC_" if info["data_class"] == "synthetic" else ""


def _clean(value: Any) -> Any:
    if isinstance(value, str):
        return ILLEGAL_CHARACTERS_RE.sub("�", value)
    if isinstance(value, (list, dict)):
        return json.dumps(value, ensure_ascii=False, sort_keys=True)
    return value


def _text_cell(ws, value: Any) -> Any:
    """Strings that would be read as formulas are forced to text; other values pass through."""
    value = _clean(value)
    if isinstance(value, str) and value.startswith("="):
        cell = WriteOnlyCell(ws, value="")
        cell.value = value
        cell.data_type = "s"
        return cell
    return value


def write_excel(tables: list[Table], info: dict[str, Any], path: Path, extra_readme: list[str] | None = None) -> Path:
    """Write the linked workbook. Returns ``path``."""
    wb = Workbook(write_only=True)
    bold = Font(bold=True)
    link_font = Font(color="0563C1", underline="single")
    warn_fill = PatternFill("solid", fgColor="FFE699")
    head_fill = PatternFill("solid", fgColor="D9D9D9")

    def styled(ws, value, font=None, fill=None, wrap=False):
        cell = WriteOnlyCell(ws, value=_clean(value))
        if font:
            cell.font = font
        if fill:
            cell.fill = fill
        if wrap:
            cell.alignment = Alignment(wrap_text=True, vertical="top")
        return cell

    readme = wb.create_sheet("README")
    readme.column_dimensions["A"].width = 34
    readme.column_dimensions["B"].width = 110
    readme.append([styled(readme, banner(info), bold, warn_fill if info["data_class"] == "synthetic"
                          or not info["protocol_confirmed"] else None)])
    readme.append([])
    lines: list[tuple[str, Any]] = [
        ("Generated (UTC)", utc_now()), ("Generated by", f"GEODESIC {__version__}"),
        ("Project", info["project_name"]), ("Project ID", info["project_id"]),
        ("Data class", info["data_class"]), ("Protocol version", info["protocol_version"]),
    ]
    c = info["counts"]
    lines += [("Reports (papers)", c["reports"]), ("  of which unresolved citations", c["reports_unresolved"]),
              ("Studies", c["studies"]), ("Experiments", c["experiments"]), ("Findings", c["findings"]),
              ("  findings not assigned to an experiment", c["findings_without_experiment"]),
              ("  findings without a stage", c["findings_without_stage"]),
              ("  findings by review status", ", ".join(f"{k}: {v}" for k, v in
                                                       sorted(c["findings_by_review_status"].items())) or "none"),
              ("Audit events", info["audit_events"])]
    for k, v in lines:
        readme.append([styled(readme, k, bold), _text_cell(readme, v)])
    readme.append([])
    notes = [
        "How to read this workbook",
        "Reports, studies, experiments and findings are different things and are counted separately.",
        "Findings imported from a workbook are imported summaries: they are evidence to verify against the "
        "original papers, not independently verified facts. Only review_status 'verified' records a reviewer's "
        "confirmation, and it applies to the stated version of the finding only.",
        "Literal columns (value_literal, unit_original, ...) hold strings exactly as written in the source; "
        "numeric columns are parsed from them. Ranges and bounds are never reduced to a single number.",
        "Row 1 of each table sheet is a banner, row 2 the header; data start in row 3. ID columns that refer to "
        f"another sheet are hyperlinks (first {EXCEL_MAX_LINKS_PER_SHEET:,} rows of each sheet).",
        "This workbook does not claim that the underlying literature search was exhaustive.",
        *(extra_readme or []),
    ]
    for i, n in enumerate(notes):
        readme.append([styled(readme, n, bold if i == 0 else None, wrap=True)])
    readme.append([])
    readme.append([styled(readme, "Sheet", bold), styled(readme, "Contents", bold)])
    for t in tables:
        readme.append([styled(readme, t.name), styled(readme, f"{t.title} ({len(t.rows):,} rows). {t.note}",
                                                        wrap=True)])

    # row number of each key (first column) per table, for hyperlinks
    index: dict[str, dict[Any, int]] = {}
    for t in tables:
        if any(t.name == target for other in tables for target in other.links.values()):
            key = t.columns[0]
            index[t.name] = {r[key]: i for i, r in enumerate(t.rows, start=EXCEL_FIRST_DATA_ROW)}
    for t in tables:
        ws = wb.create_sheet(t.name[:31])
        for i, col in enumerate(t.columns, start=1):
            ws.column_dimensions[get_column_letter(i)].width = _WIDE.get(col, max(12, min(24, len(col) + 2)))
        ws.freeze_panes = f"B{EXCEL_FIRST_DATA_ROW}"
        ws.append([styled(ws, banner(info), bold, warn_fill)])
        ws.append([styled(ws, col, bold, head_fill) for col in t.columns])
        n_links = 0
        truncated = len(t.rows) > EXCEL_MAX_ROWS - EXCEL_HEADER_ROW
        for r in t.rows[:EXCEL_MAX_ROWS - EXCEL_HEADER_ROW]:
            out = []
            for col in t.columns:
                v = r.get(col)
                target = t.links.get(col)
                row_no = index.get(target, {}).get(v) if target and v is not None else None
                if row_no and n_links < EXCEL_MAX_LINKS_PER_SHEET:
                    cell = WriteOnlyCell(ws, value=_clean(v))
                    cell.hyperlink = Hyperlink(ref="", location=f"'{target[:31]}'!A{row_no}", display=str(v))
                    cell.font = link_font
                    out.append(cell)
                    n_links += 1
                else:
                    out.append(_text_cell(ws, v))
            ws.append(out)
        if t.rows:
            last = min(len(t.rows), EXCEL_MAX_ROWS - EXCEL_HEADER_ROW) + EXCEL_HEADER_ROW
            ws.auto_filter.ref = f"A{EXCEL_HEADER_ROW}:{get_column_letter(len(t.columns))}{last}"
        if truncated:
            readme.append([styled(readme, f"NOTE: sheet '{t.name}' holds only the first "
                                          f"{EXCEL_MAX_ROWS - EXCEL_HEADER_ROW:,} of {len(t.rows):,} rows (Excel row "
                                          "limit); the CSV export is complete.", bold, warn_fill)])
    wb.properties.title = banner(info)
    wb.properties.creator = f"GEODESIC {__version__}"
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


def write_csv(table: Table, info: dict[str, Any], path: Path) -> Path:
    """Write one table as CSV (UTF-8, header row, trailing ``data_class`` column)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow([*table.columns, "data_class"])
        for r in table.rows:
            w.writerow([_csv_value(r.get(c)) for c in table.columns] + [info["data_class"]])
    return path


def _csv_value(v: Any) -> Any:
    if v is None:
        return ""
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (list, dict)):
        return json.dumps(v, ensure_ascii=False, sort_keys=True)
    return v


def write_json(tables: list[Table], info: dict[str, Any], path: Path) -> Path:
    """Write all tables as one JSON document."""
    doc = {
        "label": banner(info),
        "generated_at": utc_now(),
        "generated_by": f"GEODESIC {__version__}",
        "project": info,
        "tables": {t.name: {"title": t.title, "note": t.note, "columns": t.columns, "rows": t.rows,
                            "references": t.links} for t in tables},
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(doc, ensure_ascii=False, indent=1, sort_keys=False), encoding="utf-8")
    return path


def _ris_line(tag: str, value: Any) -> str:
    text = " ".join(str(value).split())
    return f"{tag}  - {text}"


def write_ris(paper_rows: list[dict[str, Any]], info: dict[str, Any], path: Path) -> Path:
    """Write references in RIS format (one record per paper row from ``papers_table``)."""
    out: list[str] = []
    for p in paper_rows:
        has_journal = bool(p.get("journal"))
        out.append(_ris_line("TY", "JOUR" if has_journal else "GEN"))
        for a in (p.get("authors") or "").split("; "):
            if a.strip():
                out.append(_ris_line("AU", a))
        title = p.get("title")
        if title:
            out.append(_ris_line("TI", title))
        elif p.get("citation_text"):
            out.append(_ris_line("TI", f"[citation as imported] {p['citation_text']}"))
        if has_journal:
            out.append(_ris_line("JO", p["journal"]))
        if p.get("year"):
            out.append(_ris_line("PY", p["year"]))
        if p.get("doi"):
            out.append(_ris_line("DO", p["doi"]))
        if p.get("pmid"):
            out.append(_ris_line("AN", f"PMID:{p['pmid']}"))
        for u in (p.get("urls") or "").split("; "):
            if u.strip():
                out.append(_ris_line("UR", u))
        note = [f"GEODESIC paper {p['paper_id']}", f"identifier status: {p['resolution_status']}",
                f"identity: {p['identity_status']}", p.get("correction_retraction") or ""]
        if info["data_class"] == "synthetic":
            note.insert(0, SYNTHETIC_LABEL)
        out.append(_ris_line("N1", "; ".join(n for n in note if n)))
        out.append("ER  - ")
        out.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out), encoding="utf-8")
    return path
