"""Write docs/DEPENDENCY_LICENSES.md from the metadata of the installed packages.

Usage:  python scripts/dependency_licenses.py [output file]

The licence shown is what each installed distribution declares about itself
(License-Expression, else the License field, else its licence classifiers).
It is a record, not a legal review.
"""

from __future__ import annotations

import re
import sys
from importlib import metadata as md
from pathlib import Path

DIRECT = ("openpyxl", "pandas", "pydantic", "httpx", "pypdf", "defusedxml", "PyYAML", "streamlit", "matplotlib")
DEV = ("pytest", "pillow")


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def declared(meta) -> str:
    expr = meta.get("License-Expression")
    if expr:
        return expr
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    text = (meta.get("License") or "").strip()
    if text and len(text) <= 40 and "\n" not in text:
        return text if not classifiers or text in classifiers else f"{text} ({'; '.join(classifiers)})"
    if classifiers:
        return "; ".join(classifiers)
    return "see the package's licence file" if text else "not declared in package metadata"


def main(out: Path) -> None:
    dists = {}
    for d in md.distributions():
        name = d.metadata["Name"]
        if name and norm(name) != "geodesic":
            dists[norm(name)] = (name, d.version, declared(d.metadata))
    role = {norm(n): "runtime (declared in pyproject.toml)" for n in DIRECT}
    role.update({norm(n): "development / tests" for n in DEV})
    lines = ["# Dependency licences", "",
             "Generated by `python scripts/dependency_licenses.py` from the metadata of the packages installed in the",
             "environment the test suites were run in. Each licence is what the package declares about itself; this",
             "is a record, not a legal review. Re-run the script after changing the environment.", "",
             f"Python {sys.version.split()[0]}; SQLite (bundled with Python) is in the public domain.", "",
             "## Direct dependencies", "", "| Package | Version | Declared licence | Role |", "|---|---|---|---|"]
    for key in [norm(n) for n in (*DIRECT, *DEV)]:
        if key in dists:
            name, version, lic = dists[key]
            lines.append(f"| {name} | {version} | {lic} | {role[key]} |")
        else:
            lines.append(f"| {key} | not installed | | {role[key]} |")
    lines += ["", "## Installed with them (transitive)", "", "| Package | Version | Declared licence |", "|---|---|---|"]
    for key in sorted(dists):
        if key not in role:
            name, version, lic = dists[key]
            lines.append(f"| {name} | {version} | {lic} |")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(dists)} packages)")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / "docs" / "DEPENDENCY_LICENSES.md")
